const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs'), crypto = require('crypto');
const base = process.env.POSTMARK_URL || 'http://127.0.0.1:18766';
fs.mkdirSync('work/browser', {recursive:true});
const hash = text => crypto.createHash('sha256').update(text).digest('hex');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.PW_CHROME || undefined});
  const page = await browser.newPage({viewport:{width:1440,height:1080},acceptDownloads:true});
  const errors = [], external = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', request => { if (!request.url().startsWith(base)) external.push(request.url()); });
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const waitForFinished = async () => {
    await page.waitForFunction(() => {const button=document.querySelector('#analyze');return !button.disabled && button.textContent==='Inspect this email';});
  };
  const inspect = async () => { await page.getByRole('button',{name:'Inspect this email',exact:true}).click(); await waitForFinished(); };
  const sample = async name => { await page.getByRole('button',{name,exact:true}).click(); await waitForFinished(); };
  const exportJSON = async (filename='work/browser-export.json') => {
    const event = page.waitForEvent('download');
    await page.getByRole('button',{name:'Export report JSON',exact:true}).click();
    await (await event).saveAs(filename);
    return JSON.parse(fs.readFileSync(filename,'utf8'));
  };
  const delayNext = async () => {
    let release, entered;
    const gate = new Promise(resolve => {release=resolve;});
    const seen = new Promise(resolve => {entered=resolve;});
    await page.route('**/api/analyze', async route => {
      const response = await route.fetch(); entered(); await gate;
      try { await route.fulfill({response}); } catch (_) { /* An aborted obsolete request may no longer accept a response. */ }
    }, {times:1});
    return {release,seen};
  };
  await page.goto(base); await page.getByRole('button',{name:'Password request',exact:true}).waitFor();
  await page.screenshot({path:'work/browser/desktop-empty.png',fullPage:true});
  assert(await page.locator('h1').filter({visible:true}).textContent() === 'Inspect email','Operational heading missing');
  checks.push('Compact desktop task surface and empty state');
  await inspect(); await page.getByRole('alert').filter({hasText:'Import an .eml'}).waitFor();
  checks.push('Empty input has an actionable validation error');
  await sample('Password request'); await page.getByRole('heading',{name:'High concern',exact:true}).waitFor();
  const sampleSource=await page.locator('#raw').inputValue();
  await page.screenshot({path:'work/browser/desktop-result.png',fullPage:true});
  checks.push('Synthetic sample produces populated evidence');
  await page.getByRole('tab',{name:'Links (2)',exact:true}).click();
  await page.getByText('Visible link host differs from the destination host',{exact:true}).waitFor();
  assert(await page.locator('#report-body a').count()===0,'Message link is actionable');
  await page.screenshot({path:'work/browser/desktop-links.png',fullPage:true});
  checks.push('Link mismatch remains visible with inert destinations');
  await page.getByRole('tab',{name:'Headers',exact:true}).focus(); await page.keyboard.press('ArrowRight');
  assert(await page.getByRole('tab',{name:'Model',exact:true}).getAttribute('aria-selected')==='true','Arrow navigation failed');
  checks.push('Report tab keyboard focus and arrow navigation');
  const exported=await exportJSON();
  assert(exported.message.sha256===hash(sampleSource),'JSON export does not match analyzed source bytes');
  assert(exported.message.subject===await page.locator('.subject').textContent(),'JSON subject differs from UI');
  assert((await page.locator('.score').textContent()).startsWith(String(exported.rules.score)),'JSON score differs from UI');
  checks.push('JSON export hash, subject and score match the displayed result');
  const csvEvent=page.waitForEvent('download'); await page.getByRole('button',{name:'Export link evidence CSV',exact:true}).click();
  await (await csvEvent).saveAs('work/browser-links.csv');
  const csv=fs.readFileSync('work/browser-links.csv','utf8');
  assert(csv.split('\r\n').length-1===exported.message.links.length && csv.includes('hxxps://'),'CSV evidence mismatch');
  checks.push('Defanged CSV has the displayed result link count');
  await page.getByRole('button',{name:'Model evidence',exact:true}).click();
  await page.getByRole('heading',{name:'Confusion matrix',exact:true}).waitFor();
  await page.screenshot({path:'work/browser/desktop-evaluation.png',fullPage:true});
  const evalEvent=page.waitForEvent('download'); await page.getByRole('button',{name:'Export evaluation',exact:true}).click();
  await (await evalEvent).saveAs('work/browser-evaluation.json');
  assert(JSON.parse(fs.readFileSync('work/browser-evaluation.json')).model_metrics.false_positive===7,'Wrong evaluation exported');
  checks.push('Compact evaluation retains measured matrix, errors and export');
  await page.getByRole('button',{name:'Inspect email',exact:true}).click();
  assert(await page.locator('#raw').inputValue()===sampleSource,'Navigation lost source');
  assert(await page.getByRole('tab',{name:'Model',exact:true}).getAttribute('aria-selected')==='true','Navigation lost selected report tab');
  checks.push('View navigation preserves source, result and selected evidence tab');
  await page.getByRole('button',{name:'Mailbox watch',exact:true}).click();
  await page.getByRole('heading',{name:'Synthetic adapter fixture',exact:true}).waitFor();
  await page.screenshot({path:'work/browser/desktop-watch.png',fullPage:true});
  checks.push('Mailbox fixture state, observation rows and setup disclosures');
  await page.getByRole('button',{name:'Inspect email',exact:true}).click();
  await page.locator('#raw').fill('not an email');
  assert(await page.locator('#export-report').isDisabled() && await page.locator('#export-links').isDisabled(),'Editing left old exports enabled');
  await inspect(); await page.getByRole('alert').filter({hasText:'No email headers found'}).waitFor();
  assert(await page.locator('#raw').inputValue()==='not an email','Invalid input was lost');
  assert(await page.locator('.subject').textContent()===exported.message.subject,'Error erased the prior report');
  assert(await page.locator('#export-report').isDisabled(),'Failed input enabled old export');
  await page.screenshot({path:'work/browser/desktop-error.png',fullPage:true});
  checks.push('Edited/failed input retains source and explicitly stale report with exports disabled');
  await page.locator('#raw').fill(sampleSource); await inspect();
  assert(!await page.locator('#export-report').isDisabled(),'Recovery did not enable current export');
  checks.push('Corrected input recovers to a current exportable report');

  let delay=await delayNext();
  await page.getByRole('button',{name:'Inspect this email',exact:true}).click(); await delay.seen;
  assert(await page.locator('#export-report').isDisabled(),'Pending request left exports enabled');
  const edited='From: editor@example.org\nSubject: Current edited message\n\nA meeting notice.';
  await page.locator('#raw').fill(edited); delay.release(); await page.waitForTimeout(100);
  assert(await page.locator('#raw').inputValue()===edited && await page.locator('#export-report').isDisabled(),'Late response committed after edit');
  await inspect(); let latest=await exportJSON(); assert(latest.message.sha256===hash(edited),'Edited source exported stale bytes');
  checks.push('Delayed response after edit is cancelled/ignored; next export matches edited bytes');

  delay=await delayNext(); await page.getByRole('button',{name:'Inspect this email',exact:true}).click(); await delay.seen;
  await page.locator('#file').setInputFiles('corpus/b13-0.eml'); await page.getByText(/original bytes preserved/).waitFor();
  delay.release(); await page.waitForTimeout(100);
  assert(await page.locator('#export-report').isDisabled(),'Import left stale exports enabled');
  await inspect(); await page.getByRole('heading',{name:'Few rule signals',exact:true}).waitFor();
  latest=await exportJSON(); assert(latest.message.sha256===hash(fs.readFileSync('corpus/b13-0.eml')),'Imported bytes not preserved');
  checks.push('Import invalidates delayed result and original-byte export matches imported file');

  delay=await delayNext(); await page.getByRole('button',{name:'Password request',exact:true}).click(); await delay.seen;
  await sample('Legitimate urgent notice'); delay.release(); await page.waitForTimeout(100);
  await page.getByRole('heading',{name:'Few rule signals',exact:true}).waitFor();
  latest=await exportJSON(); assert(latest.message.subject==='Urgent room closure','Late sample response replaced newer sample');
  checks.push('New sample supersedes pending sample; late response cannot overwrite it');

  await page.locator('#raw').fill('From: attacker@example.org\nSubject: <script>window.pwned=true</script>\nContent-Type: text/html\n\n<img src="https://outside.invalid/track"><script>window.pwned=true</script><a href="javascript:alert(1)">click</a>');
  await inspect(); await page.locator('.subject').filter({hasText:'window.pwned'}).waitFor();
  await page.getByRole('tab',{name:'Message',exact:true}).click();
  assert(!await page.evaluate(()=>Boolean(window.pwned)),'Injected script executed');
  checks.push('Hostile HTML stays text; scripts and remote images do not execute/load');

  await page.setViewportSize({width:390,height:844}); await page.getByRole('button',{name:'Clear',exact:true}).click();
  await page.screenshot({path:'work/browser/mobile-empty.png',fullPage:true});
  await sample('Password request'); await page.getByRole('heading',{name:'High concern',exact:true}).waitFor();
  assert(!await page.locator('#source-panel').evaluate(el=>el.open),'Mobile source did not collapse after successful inspection');
  assert((await page.locator('#report').boundingBox()).y<100,'Mobile result not reached promptly');
  await page.screenshot({path:'work/browser/mobile-result.png',fullPage:true});
  checks.push('390px empty/populated states; successful result collapses source and receives focus');
  await page.locator('#source-panel > summary').click(); await page.locator('#raw').fill('broken email on mobile'); await inspect();
  await page.getByRole('alert').filter({hasText:'No email headers found'}).waitFor();
  assert(await page.locator('#raw').inputValue()==='broken email on mobile','Mobile error discarded input');
  assert(await page.locator('#export-report').isDisabled(),'Mobile error left stale export active');
  await page.screenshot({path:'work/browser/mobile-error.png',fullPage:true});
  await page.locator('#raw').fill(sampleSource); await inspect(); latest=await exportJSON();
  assert(latest.message.sha256===hash(sampleSource),'Mobile recovery exported wrong source');
  checks.push('390px recoverable failure preserves input and safely recovers exports');
  await page.getByRole('tab',{name:'Links (2)',exact:true}).click();
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),'Long link overflow on mobile');
  await page.screenshot({path:'work/browser/mobile-links.png',fullPage:true});
  checks.push('Long URL evidence wraps without horizontal page overflow at 390px');
  await page.getByRole('button',{name:'Model evidence',exact:true}).click();
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),'Mobile evaluation overflows');
  await page.screenshot({path:'work/browser/mobile-evaluation.png',fullPage:true});
  await page.getByRole('button',{name:'Mailbox watch',exact:true}).click(); await page.getByRole('heading',{name:'Synthetic adapter fixture',exact:true}).waitFor();
  await page.screenshot({path:'work/browser/mobile-watch.png',fullPage:true});
  await page.getByRole('button',{name:'Inspect email',exact:true}).click();
  assert(await page.getByRole('tab',{name:'Links (2)',exact:true}).getAttribute('aria-selected')==='true','Mobile navigation lost report context');
  checks.push('390px evaluation/watch fit naturally and return preserves selected report');
  assert(errors.length===0,'Browser exceptions: '+errors.join('; ')); assert(external.length===0,'Unexpected external requests');
  checks.push('No browser exceptions or external requests');
  fs.writeFileSync('work/browser/browser-verification.json',JSON.stringify({timestamp:new Date().toISOString(),browser:'Chromium via Playwright, headless',checks,errors,external_requests:external,viewports:[{width:1440,height:1080},{width:390,height:844}]},null,2)+'\n');
  console.log(JSON.stringify(checks,null,2)); await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
